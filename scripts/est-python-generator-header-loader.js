/**
 * Remove OpenBlock's branding comment from generated Python. It is only a
 * source marker and has no effect on Python syntax or EST execution.
 * @param {string} source - OpenBlock's compressed Python generator.
 * @returns {string} transformed generator source.
 */
module.exports = function (source) {
    const generatedByHeader = '"# generated by OpenBlock\\n"';
    if (!source.includes(generatedByHeader)) {
        throw new Error('Unable to locate the OpenBlock generated-code header.');
    }
    return source.replace(generatedByHeader, '""');
};
