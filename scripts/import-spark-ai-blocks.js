/* eslint-disable global-require */
// Preserve the audited 1.1.9 catalog and apply the verified 1.1.10 toolbox delta.
const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');

const root = path.resolve(__dirname, '..');
const extraction = path.resolve(process.argv[2] || path.join(__dirname, 'import-data/spark-ai'));
const source = JSON.parse(fs.readFileSync(path.join(extraction, 'visible-blocks/blocks.json'), 'utf8'));
if (source.static_count !== 66 || source.conditional_count !== 13) throw new Error('Unexpected Spark catalog');
const delta = require('./spark-ai-1.1.10-delta.json');
const fixedRows = [...source.rows.slice(0, source.static_count)];
delta.blocks.forEach(row => {
    const next = fixedRows.findIndex(item => item.type === 'sensing_ultrasonic_judgment');
    fixedRows.splice(next < 0 ? fixedRows.length : next, 0, row);
});
const rows = [...fixedRows, ...source.rows.slice(source.static_count)];
const output = path.join(root, 'src/renderer/spark-ai');
fs.mkdirSync(output, {recursive: true});
const fixedIds = new Set(fixedRows.map(row => row.type));
const shadowIds = new Set(Object.keys(source.input_shadow_definitions));
const media = process.argv[3] || path.join(extraction, 'media');
const scopedIds = new Set([...fixedIds, ...shadowIds]);
const scope = id => (scopedIds.has(id) ? `spark_${id}` : id);

const assets = value => {
    if (Array.isArray(value)) return value.map(assets);
    if (!value || typeof value !== 'object') return value;
    return Object.fromEntries(Object.entries(value).map(([key, item]) => {
        if (key === 'src' && typeof item === 'string' && item.startsWith('media/')) {
            const inSource = path.join(extraction, 'source/node_modules/scratch-blocks', item);
            const file = fs.existsSync(inSource) ? inSource : path.join(media, item.slice(6));
            return [key, `data:image/svg+xml;base64,${fs.readFileSync(file).toString('base64')}`];
        }
        return [key, assets(item)];
    }));
};
const catalog = {
    source: {software: delta.software,
        extraction: delta.extraction,
        baseline: delta.baseline,
        firmwareVersion: delta.firmwareVersion,
        fixed: fixedRows.length,
        conditional: source.conditional_count},
    blocks: fixedRows.map(row => ({
        id: row.type,
        category: row.category_id,
        definition: assets(row.block_definition),
        fields: row.default_fields,
        inputs: row.inputs.filter(input => input.shadow).map(input => ({
            name: input.name, type: input.shadow.type, fields: input.shadow.fields
        }))
    })),
    shadows: Object.entries(source.input_shadow_definitions).map(([id, item]) => ({
        id, definition: assets(item.definition.json)
    }))
};
fs.writeFileSync(path.join(output, 'catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);

const generators = [...rows.map(row => [row.type, row.generator_js]),
    ...Object.entries(source.input_shadow_definitions).map(([id, item]) => [id, item.generator_js])];
const assignments = generators.map(([id, fn]) => `Blockly.Python[${JSON.stringify(scope(id))}] = ${fn};`).join('\n');
const transformed = babel.transformSync(assignments, {
    babelrc: false,
    configFile: false,
    plugins: [() => ({visitor: {
        StringLiteral (p) {
            if (scopedIds.has(p.node.value)) p.node.value = scope(p.node.value);
        },
        ObjectProperty (p) {
            if (!p.node.computed && p.node.key.type === 'Identifier' && scopedIds.has(p.node.key.name)) {
                p.node.key.name = scope(p.node.key.name);
            }
        }
    }})]
}).code;
fs.writeFileSync(path.join(output, 'source-generators.js'),
    `${'// Generated by scripts/import-spark-ai-blocks.js from Spark AI 1.1.9 + the verified 1.1.10 delta.\n' +
    '// Original API spellings are intentional; integration corrections live in python-generator.js.\n' +
    '/* eslint-disable */\nexport default function installSourceGenerators (Blockly) {\n'}${transformed}\n}\n`);
const fixtures = rows.map(row => ({id: scope(row.type),
    sourceId: row.type,
    python: row.python,
    variants: row.variants,
    notes: row.notes}));
fs.writeFileSync(path.join(root, 'scripts/spark-ai-source-fixtures.json'), `${JSON.stringify(fixtures, null, 2)}\n`);
console.log(`Imported ${catalog.blocks.length} blocks, ${catalog.shadows.length} shadows, ` +
    `${generators.length} generators.`);
